import { launchE2E } from './_e2e_browser.mjs';
const browser = await launchE2E();
const page = await browser.newPage();
await page.setCacheEnabled(false);
const resp = await page.goto('http://127.0.0.1:52024/api/status', { waitUntil: 'networkidle0', timeout: 15000 });
const headers = resp.headers();
console.log('X-Content-Type-Options:', headers['x-content-type-options']);
console.log('X-Frame-Options:', headers['x-frame-options']);
console.log('Referrer-Policy:', headers['referrer-policy']);
console.log('Cache-Control:', headers['cache-control']);
await browser.close();
